from docx import Document

def export_report_to_docx(report_text: str, output_path: str = "OpenEdge_Compliance_Audit_Report.docx"):
    """
    Takes the raw string report generated by Llama 3.1 and formats it into a professional Word document.
    """
    doc = Document()
    doc.add_heading("OpenEdge Security & Compliance Audit Report", level=1)
    doc.add_paragraph("Generated autonomously via Agentic RAG (Llama 3.1 + ChromaDB ReAct Loop).")
    
    # Split report text into paragraphs/sections
    for line in report_text.split("\n"):
        if line.startswith("# ") or line.startswith("1. ") or line.startswith("2. ") or line.startswith("3. ") or line.startswith("4. "):
            doc.add_heading(line, level=2)
        else:
            doc.add_paragraph(line)
            
    doc.save(output_path)
    print(f"[+] Report successfully exported and saved to: {output_path}")
    return output_path